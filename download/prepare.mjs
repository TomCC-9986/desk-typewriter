// Split the installers into <=20 MiB parts under public/releases/<ver>/ (Workers static assets cap files at 25 MiB)
// and write src/manifest.ts with each build's size and part sizes. Usage: node prepare.mjs
import { createReadStream, mkdirSync, rmSync, statSync, writeFileSync, readFileSync, cpSync, openSync, readSync, closeSync } from "node:fs";
const PART = 20 * 1024 * 1024;
const V = /VERSION = "(.+?)"/.exec(readFileSync("src/releases.ts", "utf8"))[1];
const SRC = { "mac-arm64": "../安装包/桌面打字机-Mac(M芯片).dmg", "mac-x64": "../安装包/桌面打字机-Mac(Intel芯片).dmg", win: "../安装包/桌面打字机-Windows安装.exe" };
rmSync("public", { recursive: true, force: true });
mkdirSync(`public/releases/${V}`, { recursive: true });
cpSync("assets", "public/assets", { recursive: true });
const manifest = {};
const buf = Buffer.alloc(PART);
for (const [id, path] of Object.entries(SRC)) {
  const size = statSync(path).size, parts = [];
  const fd = openSync(path, "r");
  for (let off = 0, i = 0; off < size; off += PART, i++) {
    const n = readSync(fd, buf, 0, Math.min(PART, size - off), off);
    const name = `/releases/${V}/${id}.part${String(i).padStart(3, "0")}`;
    writeFileSync(`public${name}`, buf.subarray(0, n));
    parts.push([name, n]);
  }
  closeSync(fd);
  manifest[id] = { size, parts };
  console.log(id, (size / 1048576).toFixed(1), "MB in", parts.length, "parts");
}
writeFileSync("src/manifest.ts", `// generated by prepare.mjs — do not edit\nexport const MANIFEST: Record<string, { size: number; parts: [string, number][] }> = ${JSON.stringify(manifest, null, 1)};\n`);
